def to1d(a):
    return np.asarray(a).ravel()
    # Converts any array-like input to a flattened 1-D NumPy array.

def build_lag_matrix(vals, maxlag=3):

    """
    Build lagged features for supervised learning.
    X[t,j] = value at time t - (j+1)
    y[t]   = value at current time t
    """

    vals = to1d(vals)
    n = len(vals)
    if n <= maxlag:
        return np.empty((0, maxlag)), np.empty((0,))
        # If not enough data points, return empty arrays.

    y = vals[maxlag:]  # Target values start after 'maxlag' steps.
    # Each column j is the series shifted by j+1 lags.
    X_cols = [vals[maxlag-(j+1): n-(j+1)] for j in range(maxlag)]
    X = np.column_stack(X_cols)
    return X, y

def fit_sarimax(train_vals, steps, seasonal_m=5):

    """
    Fits a SARIMAX model and forecasts a specified number of steps ahead.
    Tries multiple common (p,d,q) and seasonal (P,D,Q,m) orders.
    Returns a NumPy array of forecasts.
    """

    train_vals = to1d(train_vals)
    trials = [((1,1,1),(1,1,1,seasonal_m)),
              ((0,1,1),(0,1,1,seasonal_m)),
              ((1,1,0),(1,1,0,seasonal_m))]
    for order, sorder in trials:
        try:
            model = SARIMAX(train_vals, order=order, seasonal_order=sorder,
                            enforce_stationarity=False, enforce_invertibility=False)
            res = model.fit(disp=False)           # Fit quietly (no console output).
            fc = res.forecast(steps=steps)        # Forecast ahead by 'steps'.
            return to1d(fc)
        except Exception:
            continue   # If fitting fails, try the next (order, sorder) pair.
    return np.full(steps, np.nan)  # Fallback: array of NaNs if all trials fail.

