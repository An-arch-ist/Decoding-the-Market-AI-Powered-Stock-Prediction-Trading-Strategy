import pandas as pd      # for handling data
import numpy as np       # for math
import matplotlib.pyplot as plt # for plotting graphs

from sklearn.svm import SVC, SVR    # support vector classifier & Regressor
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler  # NEW: For scaling
from sklearn.metrics import accuracy_score, mean_absolute_error, mean_squared_error, r2_score, classification_report

#for time series model
from statsmodels.tsa.statespace.sarimax import SARIMAX

#gradient boosting model
import xgboost as xgb

# NEW: For dates
from datetime import datetime, timedelta

# NEW: For folders (Fixes save error)
import os

# Notebook setup
# %matplotlib inline
import warnings
warnings.filterwarnings('ignore')

# FIXED: Auto-create folders (No more "Cannot save file" error)
os.makedirs('data', exist_ok=True)    # Creates 'data/' if missing
os.makedirs('outputs', exist_ok=True)  # Creates 'outputs/' if missing
print("✓ Folders 'data/' and 'outputs/' created/verified.")

# Step 2: Download 2 year Stock market price of 10 different stocks from 10 different industries.
"""
Oil: Oil and Natural Gas Corporation Ltd
Renewable Energy: Adani Green Energy Ltd
Core Banking: Canara Bank
Metals: JSW Steel Ltd
Commodities: ITC Ltd
Real estate: DLF Ltd
Software Service: Tata Consultancy Services Ltd
Manufacturing: Larsen & Toubro Ltd
Power: NTPC Ltd (National Thermal Power Corporation Ltd)
NBFC: Bajaj Finance Ltd
"""

stocks_list = [
    "ONGC.NS","ADANIGREEN.NS","CANBK.NS","JSWSTEEL.NS","ITC.NS",
    "DLF.NS","TCS.NS","LT.NS","NTPC.NS","BAJFINANCE.NS"
]

# Download all stock data (IN Loop)
end_date = datetime.now()
start_date = end_date - timedelta(days=730)
data_dict = {}
for i, ticker in enumerate(stocks_list):
    print(f"Downloading {ticker}...")
    df = yf.download(ticker, start=start_date, end=end_date, progress=False, interval="1d")
    df = df.dropna()
    if not df.empty:
        df['Ticker'] = ticker
        data_dict[ticker] = df
        df.to_csv(f'data/{ticker}.csv')
        print("Data for:", ticker)
        print(df.head())
    else:
        print(f"No data found for {ticker}")

print(f"\nDownloaded {len(data_dict)} stocks.")

"""## **2. Feature Engineering**"""

def engineer_features(df):
    """Generate engineered features for a stock DataFrame and align target."""
    df = df.copy()  # Avoid modifying the original DataFrame

# Feature engineering
    # -----------------------------
    df["Open-Close"] = df["Open"] - df["Close"]  # Price change within the day
    df["High-Low"]   = df["High"] - df["Low"]    # Intraday volatility measure

# New: Daily return
    df['Return_1d'] = df['Close'].pct_change(1)

# Target: Next-day return
    df['Return_next'] = df['Close'].shift(-1) / df['Close'] - 1

# Drop NaNs before creating classification target (ensures proper alignment)
    df.dropna(inplace=True)

# Classification target: 1 if next-day return > 0 else 0
    y_class = np.where(df['Return_next'] > 0, 1, 0)

# Remove last row to align X and y_class (last row has NaN in Return_next after shift)
    df = df.iloc[:-1].copy()
    y_class = y_class[:-1]

# Selected features for modeling
    features = ["Open-Close", "High-Low", 'Return_1d']
    X = df[features]

# Debug check: ensure feature-target lengths match
    print(f"  Debug: len(X)={len(X)}, len(y_class)={len(y_class)}")
    assert len(X) == len(y_class), f"Length mismatch: X={len(X)}, y={len(y_class)}"

    return X, y_class, df

# Apply feature engineering to all available stocks
# -----------------------------
results = {}
for i, ticker in enumerate(stocks_list):
    if ticker in data_dict:
        X, y_class, df_eng = engineer_features(data_dict[ticker])
        results[ticker] = {'X': X, 'y_class': y_class, 'df': df_eng}
        print(f"Engineered {ticker}: {X.shape}")

"""## **3. Train–Test Split for Training and Prediction**"""

split_ratio = 0.8  # Train-test split proportion
splits = {}        # Dictionary to store split data for each stock

for i, ticker in enumerate(stocks_list):
    if ticker in results:
        df_len = len(results[ticker]['X'])  # Number of feature rows
        split_index = int(df_len * split_ratio)

   # Split features for classification
        X_train, X_test = results[ticker]['X'][:split_index], results[ticker]['X'][split_index:]
   # Split classification target
        y_train_class, y_test_class = results[ticker]['y_class'][:split_index], results[ticker]['y_class'][split_index:]
   # Split regression target (Close price)
        y_reg = results[ticker]['df']['Close']
        y_train_reg, y_test_reg = y_reg[:split_index], y_reg[split_index:]

   # Ensure exact alignment of test returns with X_test
        test_df = results[ticker]['df'].iloc[split_index:].copy()
        test_returns = test_df['Return_next'].values  # Already valid (no NaNs after feature engineering)

   # Debug check: confirm lengths match
        print(f"  Debug {stocks_list[i]}: len(X_test)={len(X_test)}, len(test_returns)={len(test_returns)}")
        assert len(X_test) == len(test_returns), f"Mismatch in {ticker}: X_test={len(X_test)}, returns={len(test_returns)}"

    # Store all splits and relevant data
        splits[ticker] = {
            'X_train': X_train, 'X_test': X_test,
            'y_train_class': y_train_class, 'y_test_class': y_test_class,
            'y_train_reg': y_train_reg, 'y_test_reg': y_test_reg,
            'test_returns': test_returns,
            'df': results[ticker]['df'],   # Keep full DataFrame for later
            'split_index': split_index
        }

        print(f"{stocks_list[i]} Train size: {len(X_train)}, Test size: {len(X_test)}")

"""## **4. Model Training & Prediction (SVC)**"""

from sklearn.svm import SVC
from sklearn.metrics import accuracy_score

svc_models = {}   # Store trained SVC models and scalers per stock
accuracies = []   # Store test accuracies per stock

for i, ticker in enumerate(stocks_list):
    if ticker in splits:
        split = splits[ticker]

        # Debug: ensure training feature/target lengths match
        print(f"  Debug {stocks_list[i]} train: len(X_train)={len(split['X_train'])}, len(y_train)={len(split['y_train_class'])}")
        assert len(split['X_train']) == len(split['y_train_class']), f"Train mismatch in {ticker}"

        # Scale features for SVC (important for RBF kernel)
        scaler = StandardScaler()
        X_train_scaled = scaler.fit_transform(split['X_train'])
        X_test_scaled = scaler.transform(split['X_test'])

        # Train SVC classifier
        svc = SVC(kernel="rbf")
        svc.fit(X_train_scaled, split['y_train_class'])

        # Predict and compute test accuracy
        y_pred_class = svc.predict(X_test_scaled)
        acc = accuracy_score(split['y_test_class'], y_pred_class)
        print(f"{stocks_list[i]} SVC Test Accuracy: {acc:.4f}")

        # Store model, scaler, and predictions
        svc_models[ticker] = {'svc': svc, 'scaler': scaler, 'y_pred': y_pred_class}
        accuracies.append({'Stock': stocks_list[i], 'Accuracy': acc})

# Summary of all SVC accuracies
acc_df = pd.DataFrame(accuracies)
print("\nSVC Accuracies:\n", acc_df)

# Save CSV of accuracies
acc_df.to_csv('outputs/part1_accuracies.csv', index=False)

"""## **5. SVC Return Strategy Simulation**"""

strategy_summaries = []  # Store summary metrics per stock

for i, ticker in enumerate(stocks_list):
    if ticker in splits and ticker in svc_models:
        split = splits[ticker]
        y_pred_class = svc_models[ticker]['y_pred']  # Predicted signals
        test_returns = split['test_returns']        # Actual next-day returns

  # Align df_temp with test_returns length
        df_temp = split['df'].iloc[split['split_index']: ].copy()  # Full test period
        df_temp["Predicted_Signal"] = y_pred_class
        df_temp["Return"] = test_returns

  # Strategy return = actual return * predicted signal (1 for long, 0 for no position)
        df_temp["Strategy_Return"] = df_temp["Return"] * df_temp["Predicted_Signal"]

  # Compute cumulative returns (compounded)
        df_temp["Cum_Ret"] = np.cumprod(1 + df_temp["Return"]) - 1
        df_temp["Cum_Strategy"] = np.cumprod(1 + df_temp["Strategy_Return"]) - 1

  # Plot comparison of market vs strategy cumulative returns
        plt.figure(figsize=(12,5))
        plt.plot(df_temp["Cum_Ret"], color="red", label="Actual Cumulative Returns")
        plt.plot(df_temp["Cum_Strategy"], color="blue", label="Strategy Return (SVC)")
        plt.legend()
        plt.title(f"SVC Strategy Returns Vs Actual Cumulative Returns - {stocks_list[i]} ({ticker})")
        plt.savefig(f'outputs/{stocks_list[i]}_strategy.png', dpi=150)  # Save figure
        plt.show()

  # Collect summary metrics
        final_ret = df_temp["Cum_Ret"].iloc[-1]
        final_strategy = df_temp["Cum_Strategy"].iloc[-1]
        strategy_summaries.append({
            'Stock': stocks_list[i],
            'Actual_Final': final_ret,
            'Strategy_Final': final_strategy,
            'Outperformance': final_strategy - final_ret
        })

# Create summary DataFrame
returns_df = pd.DataFrame(strategy_summaries)
print("\nStrategy Returns:\n", returns_df.round(4))

# Save summary CSV
returns_df.to_csv('outputs/part1_returns.csv', index=False)

"""## **7. Returns Comparison of SVC Predicted Equal-Weight Portfolio for mentioned 10 stocks vs Nifty 50**"""

# SVC Portfolio vs Nifty50
# --------------------------

# Download Nifty50 index data
nifty = yf.download('^NSEI', start=start_date, end=end_date, progress=False)
nifty_returns = nifty['Close'].pct_change().dropna()  # Daily returns

# Approximate test period length using first stock
test_len = len(splits[stocks_list[0]]['test_returns'])
portfolio_returns = np.zeros(test_len)  # Initialize portfolio returns

# Compute daily portfolio returns
for day in range(test_len):
    signals = []
    day_returns = []
    for j, ticker in enumerate(stocks_list):
        if ticker in splits and day < len(splits[ticker]['test_returns']):
            signal = svc_models[ticker]['y_pred'][day]   # Predicted signal (1 or 0)
            ret = splits[ticker]['test_returns'][day]    # Actual next-day return
            signals.append(signal)
            day_returns.append(ret)

# Equal-weight portfolio: average returns of stocks with buy signals
    buys = [day_returns[k] for k in range(len(signals)) if signals[k] == 1]
    port_ret = np.mean(buys) if buys else 0
    portfolio_returns[day] = port_ret

# Compute cumulative returns
cum_port = np.cumprod(1 + portfolio_returns) - 1
cum_nifty = np.cumprod(1 + nifty_returns.iloc[-test_len:].values) - 1  # Align test period

# Plot portfolio vs Nifty
plt.figure(figsize=(10,5))
plt.plot(cum_port, color="green", label="SVC Portfolio")
plt.plot(cum_nifty, color="purple", label="Nifty50")
plt.legend()
plt.title("SVC Portfolio vs Nifty50")
plt.savefig('outputs/portfolio_vs_nifty.png', dpi=150)
plt.show()

# Summary table of final cumulative returns
port_df = pd.DataFrame({
    'Metric': ['Portfolio', 'Nifty50', 'Difference'],
    'Value': [cum_port[-1], cum_nifty[-1], cum_port[-1] - cum_nifty[-1]]
})
print("\nPortfolio vs Nifty:\n", port_df.round(4))
port_df.to_csv('outputs/part1_portfolio.csv', index=False)

